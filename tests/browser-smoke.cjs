/* Floating Life events v4: test actual timeline, school, age, career and random choice. */
const fs=require('node:fs');
const assert=require('node:assert/strict');
const vm=require('node:vm');
const {JSDOM}=require('jsdom');
const html=fs.readFileSync('index.html','utf8');
const story=fs.readFileSync('story.js','utf8');
const visual=fs.readFileSync('visual.js','utf8');
const core=html.match(/<script>([\s\S]*?)<\/script>/);
assert(core&&core[1],'core script missing');
for(const [name,code] of [['story',story],['core',core[1]],['visual',visual]])new vm.Script(code,{filename:name+'.js'});
assert(html.includes('src="story.js?v=4"'),'story script must be included before core');
const dom=new JSDOM(html,{runScripts:'outside-only',pretendToBeVisual:true,url:'https://example.org/Peak-Life-Game/'});
const w=dom.window,d=w.document;
w.scrollTo=()=>{};
w.eval(story);w.eval(core[1]);w.eval(visual);
const api=w.__FUSHI_BRIDGE__,world=w.__WORLD_TEST__;
const click=s=>{const el=d.querySelector(s);assert(el,'missing '+s);assert(!el.disabled,'disabled '+s);el.click();return el};
function choice(last=true){
  const enabled=[...d.querySelectorAll('#modal [data-event-choice]')].filter(x=>!x.disabled);
  assert(enabled.length>0,'event must offer at least one enabled decision');
  const el=last?enabled.at(-1):enabled[0];el.click();
  assert.equal(api.getState().event,null,'event should resolve after choice');
}
function nextAge(){
  const s=api.getState();
  assert(!s.event,'resolve event before advancing age');
  const old=s.age;
  world.getWorld().day=360;
  world.forceDays(1);
  assert.equal(s.age,old+1,'age should advance naturally after full year');
  assert.equal(s.world.day,1,'new year starts on day 1');
}
assert(d.querySelector('[data-cmd="start"]'),'character creator not found');
click('[data-cmd="start"]');
world.tick();
const s=api.getState();
assert.equal(s.age,6,'new life should begin at age 6');
assert.equal(s.event,'age_6','first story must be school enrolment');
assert(!d.querySelector('#world-shell').classList.contains('hidden'),'town should render');
assert.equal(d.querySelectorAll('#world-people .actor').length,3,'animated characters should appear');
assert.equal(d.querySelector('#world-ap').textContent,'蒙学','age stage HUD should replace action points');
assert(!d.querySelector('[data-act]'),'no active actions should be present');
assert(!d.querySelector('[data-cmd="next"]'),'no skip-year buttons should be present');
assert(d.querySelector('#screen').textContent.includes('下一次人生大事'),'age stage must be visible');
const initialWis=s.stats.wis,initialCharm=s.stats.charm;
choice();
assert(s.school==='乡塾蒙学','first choice should enroll in school');
assert(s.stats.charm>initialCharm,'chosen school event should grow a stat');
assert.equal(s.stats.wis,initialWis,'unchosen stats should not grow');
click('[data-time-speed="4"]');assert.equal(s.world.speed,4);
click('[data-time-speed="0"]');assert.equal(s.world.speed,0);
click('[data-time-speed="1"]');assert.equal(s.world.speed,1);
const initialStats={...s.stats};
world.getWorld().day=89;
world.getWorld().eventAt=999999;
world.forceDays(3);
assert.equal(JSON.stringify(s.stats),JSON.stringify(initialStats),'passive quarterly stat increases must be removed');
const milestoneMap={10:'age_10',12:'age_12',15:'age_15',18:'age_18'};
for(let next=7;next<=18;next++){
  if(s.event)choice();
  nextAge();
  if(milestoneMap[next])assert.equal(s.event,milestoneMap[next],'age '+next+' milestone must have priority');
  else assert(s.event,'regular random event should occur between age milestones');
  choice();
}
assert.equal(s.age,18);
assert.equal(s.school,'入世谋生','adult career selection should complete');
assert.equal(s.job,'artisan','sixth choice selects artisan path');
click('[data-tab="career"]');
assert(d.querySelector('#screen').textContent.includes('学业与职业'));
assert(!d.querySelector('#screen [data-cmd="promote"]'),'career has no manual promotion');
click('[data-tab="estate"]');
assert(d.querySelector('#screen').textContent.includes('坊市与田产'));
assert(!d.querySelector('#screen [data-cmd="buy-shop"]'),'estate has no manual purchases');
click('[data-tab="family"]');
assert(d.querySelector('#screen').textContent.includes('缘分与亲人'));
assert(!d.querySelector('#screen [data-cmd="visit"]'),'family has no manual visits');
const beforeSilver=s.silver;
world.getWorld().eventAt=999999;
world.forceDays(31);
assert(s.world.incomePaid>0,'adult earnings should arrive monthly');
assert(s.silver>beforeSilver,'silver should increase automatically');
assert(d.querySelector('#world-silver').textContent.length>0,'HUD displays silver');
s.world.eventAt=s.world.globalDay+1;
world.forceDays(1);
assert(s.event&&s.event.indexOf('age_')!==0,'random events should pop up over time');
choice();
assert(!d.querySelector('[data-act]'),'action controls must remain absent');
w.close();
console.log('PASS: age-6 enrolment, age-10/12/15 school milestones, age-18 career, random event, choices, passive growth disabled, auto silver, no action buttons, all tabs and syntax');